import { existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ui } from '../core/ui.js';

const DEFAULT_AGENTS_MD = '# AGENTS.md\n\nInstructions for any coding agent working in this repo.\nGenerated by `lehrosol init`. Edit freely.\n\n## Project overview\n\n(describe the project here)\n\n## Ground rules\n\n- (add your conventions here)\n';
const DEFAULT_FIX_PLAN = '# fix_plan.md\n\nRunning backlog for the LehroSol Loop Engine. One item per line.\n\n- [ ] (add your first task here)\n';
const DEFAULT_LEHRORC = JSON.stringify({ owaspScope: ['web'], capabilityTier: 'standard' }, null, 2) + '\n';

export function runInitCommand(flags, logger) {
  const cwd = process.cwd();
  const files = [
    { path: join(cwd, 'AGENTS.md'), content: DEFAULT_AGENTS_MD, label: 'Agent instructions' },
    { path: join(cwd, 'fix_plan.md'), content: DEFAULT_FIX_PLAN, label: 'Loop Engine backlog' },
    { path: join(cwd, '.lehrorc.json'), content: DEFAULT_LEHRORC, label: 'LehroSol config' }
  ];

  ui.sectionHeader('Project Initialization');

  // Show planned files in a table
  ui.table(
    ['File', 'Purpose', 'Action'],
    files.map((f) => {
      const exists = existsSync(f.path);
      const action = exists ? (flags.force ? 'overwrite' : 'skip (exists)') : 'create';
      return [ui.filePath(f.path.split('/').pop()), f.label, action];
    })
  );

  const created = [];
  const skipped = [];

  for (const file of files) {
    if (existsSync(file.path) && !flags.force) {
      skipped.push(file.path);
      continue;
    }
    writeFileSync(file.path, file.content, 'utf8');
    created.push(file.path);
  }

  if (created.length > 0) {
    ui.success(`Created ${created.length} file(s)`);
    ui.list(
      created.map((f) => ui.filePath(f.split('/').pop() || f)),
      'Created Files'
    );
  }

  if (skipped.length > 0) {
    ui.warning(`${skipped.length} file(s) skipped`, 'Use --force to overwrite existing files');
  }

  ui.nextSteps([
    'Edit AGENTS.md to describe your project',
    'Run `lehrosol doctor` to verify the project is ready',
    'Run `lehrosol loop run --prompt "..."` to start a loop',
  ]);
}
