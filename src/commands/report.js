// lehrosol report — export a session as a shareable Markdown mission report:
// project identity, objective, iteration log, and the captured diff.
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { ui } from '../core/ui.js';
import { listSessions, getSession } from '../core/sessionStore.js';
import { projectIdentity } from '../core/projects.js';
import { digestPrompt } from '../core/engrams.js';

function verdictBadge(v) {
  if (v === 'stop-success') return '✅ PASS (stop-success)';
  if (v === 'stop-budget-exhausted') return '🟡 BUDGET EXHAUSTED';
  if (v === 'stop-adapter-error') return '❌ ADAPTER ERROR';
  if (v === 'stop-adapter-unavailable') return '⚫ ADAPTER OFFLINE';
  return v || '(unfinished)';
}

export function runReportCommand(flags, logger) {
  const sessions = listSessions({ limit: 20 });
  const id = flags.id || (sessions[0] && sessions[0].id);
  if (!id) {
    ui.error('No sessions recorded yet', 'Run one first: lehrosol loop run --prompt "..."');
    process.exitCode = 1;
    return;
  }
  const session = getSession(String(id));
  if (!session) {
    ui.error('No session found with id ' + id, 'List sessions: lehrosol sessions list');
    process.exitCode = 1;
    return;
  }

  let project = null;
  try { project = session.cwd ? projectIdentity(session.cwd) : null; } catch { project = null; }
  const checkpoints = (session.checkpoints || []).map((cp) => ({ iteration: cp.iteration, data: cp.data || cp }));
  const lastDiff = [...checkpoints].reverse().map((c) => c.data.diff).find((d) => d && !d.empty) || null;

  const lines = [];
  lines.push(`# ${project ? project.sigil + ' ' : ''}LEHRO MISSION REPORT — ${project ? `${project.codename} [${project.tag}]` : 'SESSION'}`);
  lines.push('');
  lines.push('| Field | Value |');
  lines.push('| --- | --- |');
  lines.push(`| Session | \`${session.id}\` |`);
  if (session.cwd) lines.push(`| Workspace | \`${session.cwd}\` |`);
  lines.push(`| Adapter | ${session.adapter || 'unknown'} |`);
  lines.push(`| Verdict | ${verdictBadge(session.finalVerdict)} |`);
  lines.push(`| Iterations | ${session.totalIterations != null ? session.totalIterations : checkpoints.length} |`);
  if (session.startedAt) lines.push(`| Started | ${session.startedAt} |`);
  if (session.finishedAt) lines.push(`| Finished | ${session.finishedAt} |`);
  lines.push('');
  lines.push('## Objective');
  lines.push('');
  lines.push(`> ${digestPrompt(session.prompt, 400) || '(no prompt recorded)'}`);
  lines.push('');

  if (checkpoints.length) {
    lines.push('## Iteration log');
    lines.push('');
    lines.push('| Iter | Adapter | Verdict |');
    lines.push('| --- | --- | --- |');
    for (const c of checkpoints) {
      lines.push(`| ${c.iteration} | ${c.data.adapter || session.adapter || '-'} | ${(c.data.score && c.data.score.verdict) || '-'} |`);
    }
    lines.push('');
  }

  if (lastDiff) {
    lines.push('## What changed');
    lines.push('');
    if (lastDiff.stat) {
      lines.push('```text');
      lines.push(String(lastDiff.stat).trimEnd());
      lines.push('```');
      lines.push('');
    }
    if (lastDiff.patch && lastDiff.patch.trim()) {
      const patchLines = String(lastDiff.patch).split('\n');
      const shown = patchLines.slice(0, 200);
      lines.push('```diff');
      lines.push(...shown.map((l) => l.replace(/```/g, '`\u200b``')));
      if (patchLines.length > 200) lines.push(`... (${patchLines.length - 200} more lines — see: lehrosol diff --id ${session.id} --raw)`);
      lines.push('```');
      lines.push('');
    }
    if (lastDiff.untrackedFiles && lastDiff.untrackedFiles.length) {
      lines.push('### New files');
      lines.push('');
      for (const f of lastDiff.untrackedFiles) lines.push(`- \`${f}\``);
      lines.push('');
    }
  } else {
    lines.push('## What changed');
    lines.push('');
    lines.push('_No workspace diff was captured for this session (dry run, non-git workspace, or no changes)._');
    lines.push('');
  }

  lines.push('---');
  lines.push('');
  lines.push(`_Generated by LehroSol · ${new Date().toISOString()} · replay the patch with \`lehrosol diff --id ${session.id}\`_`);

  const defaultName = `LEHRO-REPORT-${project ? project.tag : 'SESSION'}-${String(session.startedAt || new Date().toISOString()).slice(0, 10)}.md`;
  const out = resolve(String(flags.out || defaultName));
  writeFileSync(out, lines.join('\n') + '\n', 'utf8');

  ui.sectionHeader('Mission Report');
  console.log(`  Session ${String(session.id).slice(0, 8)}… → ${ui.highlight(out)}`);
  ui.nextSteps([
    'Open the report in any Markdown viewer or paste it into Notion',
    'Report a different run: lehrosol report --id <session> --out mission.md',
  ]);
}
